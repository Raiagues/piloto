/* global window, document */
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright-core';
import { buildApp } from '../server/app.mjs';

const directory = await mkdtemp(join(tmpdir(), 'norte-project-workspace-'));
const app = await buildApp({ storeFile: join(directory, 'state.json'), logger: false, mailer: { configured: false }, ai: { apiKey: '' } });
const port = 5313, base = `http://127.0.0.1:${port}/norte/`;
process.env.NORTE_ALLOWED_ORIGINS = new URL(base).origin;
let browser, vite, page;
try {
  const registration = await app.inject({ method: 'POST', url: '/api/auth/register', payload: { name: 'Engineering Captain', email: 'workspace@example.test', password: 'browser workspace test passphrase' } });
  assert.equal(registration.statusCode, 201, registration.body);
  await app.missionStore.update(data => { for (const team of data.teams) team.memberIds = team.memberIds.filter(id => id !== registration.json().user.memberId); });
  const cookies = [registration.headers['set-cookie']].flat().map(value => value.split(';')[0]);
  await app.listen({ host: '127.0.0.1', port: 0 });
  vite = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', String(port), '--strictPort'], { env: { ...process.env, VITE_DEMO_MODE: 'false', VITE_API_PROXY_TARGET: `http://127.0.0.1:${app.server.address().port}` }, stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Vite startup timeout')), 15000); vite.stdout.on('data', chunk => { if (String(chunk).includes('Local:')) { clearTimeout(timer); resolve(); } }); vite.once('exit', code => { clearTimeout(timer); reject(new Error(`Vite exited ${code}`)); }); });
  browser = await chromium.launch({ executablePath: process.env.NORTE_CHROME || '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies(cookies.map(cookie => ({ name: cookie.split('=')[0], value: cookie.slice(cookie.indexOf('=') + 1), url: new URL(base).origin })));
  await context.addInitScript(() => { if (window === window.top) window.localStorage?.setItem('norte-language', 'pt'); });
  const errors = [], extractionCalls = [];
  page = await context.newPage(); page.on('pageerror', error => errors.push(error.message)); page.on('request', request => { if (request.method() === 'POST' && /\/system-ai\/(?:jobs|generate)/.test(request.url())) extractionCalls.push(request.url()); });
  await page.goto(`${base}#/new-project`);
  await page.getByRole('button', { name: 'PT', exact: true }).click().catch(() => {});
  await page.getByLabel('Nome do projeto', { exact: true }).fill('Aurora · Engenharia');
  assert.equal(await page.locator('.project-create .sector-row').count(), 0);
  assert.equal(await page.locator('.project-create input:visible').count(), 1);
  await page.screenshot({ path: '/tmp/norte-workspace-create.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/norte-workspace-create-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Criar projeto', exact: true }).click();
  await page.getByRole('heading', { name: 'Memória do projeto', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Configuração', exact: true }).click();
  await page.getByLabel('Tipo de projeto', { exact: true }).selectOption('research');
  await page.getByLabel('Objetivo do projeto', { exact: true }).fill('Validar a arquitetura de um nanosatélite com rastreabilidade documental.');
  await page.getByText('Sugestão de setores', { exact: true }).click();
  await page.getByRole('button', { name: 'Adicionar setores sugeridos', exact: true }).click();
  await page.getByText('Setores adicionados.', { exact: false }).waitFor();
  await page.getByRole('button', { name: /^Documentos/ }).click();
  await page.locator('.memory-folders nav').getByRole('button', { name: 'Pesquisa', exact: true }).click();
  await page.getByRole('button', { name: 'Modelo de pastas', exact: true }).click();
  await page.locator('.folder-template select').selectOption('engineering');
  await page.getByRole('button', { name: 'Adicionar pastas', exact: true }).click();
  await page.locator('.folder-template').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Modelo de pastas', exact: true }).click();
  await page.getByRole('button', { name: 'Adicionar pastas', exact: true }).click();
  await page.locator('.folder-template').waitFor({ state: 'hidden' });
  const stored = Object.values(app.missionStore.read().workspace.projects).find(record => record.document.name === 'Aurora · Engenharia');
  assert.ok(stored); assert.equal(stored.document.context.folders.length, 8);
  assert.equal(stored.document.context.referenceProgram, 'independent');
  const privateTeam = app.missionStore.read().teams.find(team => team.id === stored.document.context.teamId);
  assert.deepEqual(privateTeam.memberIds, [registration.json().user.memberId]);
  assert.equal(stored.document.engineeringSystem, undefined);
  assert.equal(await page.getByRole('button', { name: 'Abrir concepção', exact: true }).isEnabled(), true);
  await page.getByRole('button', { name: 'Abrir concepção', exact: true }).click();
  await page.waitForURL(/#\/brainstorming/);
  assert.deepEqual(extractionCalls, [], 'opening conception without documents never starts a paid extraction');
  await page.evaluate(() => { window.location.hash = '#/study-setup'; });
  await page.getByRole('heading', { name: 'Memória do projeto', exact: true }).waitFor();
  await page.locator('.memory-folders nav').getByRole('button', { name: 'Datasheets', exact: true }).click();
  await page.locator('.pm-artifact-band header').getByRole('button', { name: 'Adicionar', exact: true }).click();
  await page.locator('.pm-dialog-form input[name=label]').fill('Datasheet do sensor');
  await page.getByRole('button', { name: 'Escrever documento', exact: true }).click();
  await page.locator('textarea[name=documentText]').fill('# Sensor\n\nResolução: 12 bits. Alimentação: 3,3 V.\n\nDocumento de validação local.');
  await page.locator('.pm-dialog-form button[type=submit]').click();
  await page.locator('.pm-dialog').waitFor({ state: 'hidden' });
  await page.getByRole('link', { name: 'Abrir: Datasheet do sensor', exact: true }).waitFor();
  const artifact = app.missionStore.read().artifacts.find(item => item.label === 'Datasheet do sensor');
  assert.ok(artifact.folderId); assert.match(artifact.documentText, /12 bits/);
  await page.getByRole('button', { name: 'Vincular existente', exact: true }).click();
  await page.locator('.pm-reference-picker').getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Salvar vínculos', exact: true }).click();
  await page.locator('.editor-popup').waitFor({ state: 'hidden' });
  await page.getByRole('link', { name: 'Abrir: Datasheet do sensor', exact: true }).waitFor();
  const referenceProject = app.missionStore.read().workspace.projects[stored.document.id].document;
  assert.deepEqual(referenceProject.context.programArtifactIds, [artifact.id]);
  assert.equal(referenceProject.context.folders.find(folder => folder.id === referenceProject.context.programFolderId).name, 'Edital e referências');
  assert.equal(app.missionStore.read().artifacts.filter(item => item.ownerId === referenceProject.id).length, 1, 'reference does not copy the original document');
  assert.equal(app.missionStore.read().artifacts.find(item => item.id === artifact.id).folderId, artifact.folderId);
  await page.getByRole('button', { name: 'Todos os artefatos', exact: true }).click();
  await page.getByLabel('Buscar documentos').fill('inexistente');
  await page.getByRole('heading', { name: 'Nenhum resultado' }).waitFor();
  await page.getByLabel('Buscar documentos').fill('sensor');
  await page.getByRole('link', { name: 'Abrir: Datasheet do sensor', exact: true }).click();
  await page.locator('.memory-workspace iframe').waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Baixar / abrir original', exact: true }).click();
  assert.equal(await (await downloadPromise).failure(), null);
  await page.getByRole('button', { name: 'Recolher navegação', exact: true }).click();
  await page.getByLabel('Buscar documentos').fill('');
  await page.locator('.pm-main').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: '/tmp/norte-workspace-memory.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.getByRole('link', { name: 'Abrir: Datasheet do sensor', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Mostrar ou recolher pastas' }).getAttribute('aria-expanded'), 'false');
  await page.screenshot({ path: '/tmp/norte-workspace-memory-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.getByRole('link', { name: 'Abrir: Datasheet do sensor', exact: true }).waitFor();
  assert.equal(Object.values(app.missionStore.read().workspace.projects).filter(record => record.document.name === 'Aurora · Engenharia').length, 1);
  assert.equal(app.missionStore.read().workspace.projects[stored.document.id].document.context.folders.length, 9);
  await page.getByRole('button', { name: 'Resumo', exact: true }).click();
  await page.getByText('Validar a arquitetura de um nanosatélite com rastreabilidade documental.', { exact: true }).waitFor();
  await page.getByRole('button', { name: /^Documentos/ }).click();
  await page.getByRole('button', { name: 'Ativar tema claro', exact: true }).click();
  await page.screenshot({ path: '/tmp/norte-workspace-memory-light.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: name-first project, automatic private team, independent project, explicit sectors, idempotent folders, nested upload, search, PDF reading/download, saved overview and mobile layout; no model calls.');
} catch (error) { if (page) { await page.screenshot({ path: '/tmp/norte-workspace-failed.png', fullPage: true }); console.error(await page.locator('body').innerText()); } throw error;
} finally {
  await browser?.close(); vite?.kill('SIGTERM'); await app.close(); await rm(directory, { recursive: true, force: true });
}
